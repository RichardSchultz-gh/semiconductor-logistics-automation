CREATE TABLE ENTITIES (
    ENTITY VARCHAR(50),
    "CLASS" VARCHAR(50),
    ENABLED INT,
    NOTE VARCHAR(50),
    "STATE" VARCHAR(10)
);

CREATE TABLE LOT (
    LOTID VARCHAR(15) PRIMARY KEY,
    PRIORITY INT,
    PIECES INT,
    "STATE" VARCHAR(15),
    PRODUCT VARCHAR(15),
    ROUTE VARCHAR(15),
    OPER VARCHAR(15),
    CUSTOMER VARCHAR(15),
    "ORDER" VARCHAR(15),
    DUEDATE DATE,
    STARTDATE DATE,
    ENTEROPER TIMESTAMP,
    PROCSTART TIMESTAMP,
    DISPTOOL VARCHAR(10)
);

CREATE TABLE PRODFLOW (
    PRODUCT VARCHAR(15),
    ROUTE VARCHAR(15),
    SEQ INT
);

CREATE TABLE PTIME (
    TOOL VARCHAR(15),
    PRODUCT VARCHAR(15),
    ROUTE VARCHAR(15),
    OPER VARCHAR(10),
    PTIME INT,
    "INT" INT
);

CREATE TABLE TOOL (
    TOOL VARCHAR(15),
    TOOLFAM VARCHAR(15),
    "OWNER" VARCHAR(25),
    TOOLTYPE VARCHAR(25),
    MTTR INT,
    MTTF INT,
    "STATE" VARCHAR(15)
);

CREATE TABLE WORKFLOW (
    ROUTE VARCHAR(15),
    OPER VARCHAR(10),
    "DESC" VARCHAR(255),
    MANDATORY INT,
    STEPPERC DECIMAL(10, 2)
);